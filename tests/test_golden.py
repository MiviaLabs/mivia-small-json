"""Golden test: routing/extract/emit/classify must stay byte-identical.

Pins the observable behavior of the rules layer (route, scores,
extract, emit) and of ``pipeline.classify`` with the committed router
artifact over a seeded sample of the committed corpora. The fixture
``tests/fixtures/routing-golden.jsonl`` is generated by
``tests/fixtures/make_routing_golden.py``; every refactor must
reproduce it byte for byte.

Wall-clock values are scrubbed at capture and verification time
(``ts`` fields become ``<ts>``; ``latency_ms`` is dropped from meta).
Everything else must match exactly.
"""

import json
import re
from pathlib import Path

import pytest

from mivia_small_json import pipeline, registry, rules, synth
from mivia_small_json.model import MODEL_PATH

ROOT = Path(__file__).resolve().parents[1]
GOLDEN = ROOT / "tests" / "fixtures" / "routing-golden.jsonl"

_TS_LIKE = re.compile(r"^\d{4}-\d{2}-\d{2}T")


def scrub(obj):
    """Replace wall-clock ``ts`` values with a stable marker."""
    if isinstance(obj, dict):
        return {
            k: ("<ts>" if k == "ts" and isinstance(v, str)
                and _TS_LIKE.match(v) else scrub(v))
            for k, v in obj.items()
        }
    if isinstance(obj, list):
        return [scrub(v) for v in obj]
    return obj


def keep(meta):
    """Meta without the wall-clock latency (everything behavioral)."""
    return {k: v for k, v in meta.items() if k != "latency_ms"}


@pytest.fixture(scope="module")
def router():
    loaded = pipeline.load_router(MODEL_PATH)
    assert loaded is not None, "committed router artifact failed to load"
    return loaded


def _recompute(rec: dict, model) -> dict:
    text = rec["text"]
    route = rules.route(text)
    obj, attempts, emit_schema, escaped = rules.emit(text)
    cls_obj, cls_meta = pipeline.classify(text, model)
    return {
        "src": rec["src"],
        "i": rec["i"],
        "text": text,
        "route": route,
        "scores": rules.route_scores(text),
        "extract": scrub(rules.extract(text, route)),
        "emit": {"obj": scrub(obj), "attempts": attempts,
                 "schema": emit_schema, "template_fallback": escaped},
        "classify": {"obj": scrub(cls_obj), "meta": keep(cls_meta)},
    }


def test_golden_outputs_are_byte_identical(router):
    from mivia_small_json.bootstrap import shipped_world

    with shipped_world():  # the world make_routing_golden.py captures in
        lines = GOLDEN.read_text(encoding="utf-8").splitlines(keepends=True)
        assert len(lines) > 0, "golden fixture is empty"
        for n, line in enumerate(lines):
            rec = json.loads(line)
            got = json.dumps(_recompute(rec, router), sort_keys=True,
                             ensure_ascii=True, separators=(",", ":")) + "\n"
            assert got == line, (
                f"golden row {n} ({rec['src']}#{rec['i']}) diverged: "
                "routing/extract/emit/classify behavior changed")


def test_golden_rows_match_committed_data():
    """Every fixture row must point at the committed data row."""
    data = {}
    for rec in (json.loads(line) for line
                in GOLDEN.read_text(encoding="utf-8").splitlines()):
        if rec["src"] not in data:
            rows = [json.loads(line) for line
                    in (ROOT / rec["src"]).read_text(encoding="utf-8")
                    .splitlines() if line.strip()]
            data[rec["src"]] = rows
        assert data[rec["src"]][rec["i"]]["raw"] == rec["text"], (
            f"{rec['src']}#{rec['i']} no longer matches the fixture")


def test_registration_at_import_is_idempotent():
    """Re-registering adds nothing: no duplicates, built-ins stay first."""
    before = registry.active()
    synth.register_example_schemas()
    synth.register_example_schemas()
    assert registry.active() == before
    assert len(set(registry.active())) == len(registry.active())
    assert registry.active()[:len(registry.BUILT_IN_SCHEMAS)] \
        == registry.BUILT_IN_SCHEMAS


def test_builtin_tables_serve_exactly_the_builtin_specs():
    """The declarative tables must cover every built-in, and only those.

    A missing routing key would make a built-in unroutable; a missing or
    stray defaults key can silently fall through to the rule-shape
    ladder (same '' / 0 / [] values), so the table itself is gated here.
    """
    from mivia_small_json.schemas import BUILTIN_DEFAULTS, BUILTIN_ROUTING, SPEC

    assert set(BUILTIN_ROUTING) == set(registry.BUILT_IN_SCHEMAS)
    assert set(rules.BUILTIN_EXTRACTORS) == set(registry.BUILT_IN_SCHEMAS)
    spec_fields = {f for spec in SPEC.values() for f in spec}
    assert set(BUILTIN_DEFAULTS) <= spec_fields
    for spec in SPEC.values():
        for field, rule in spec.items():
            if field == "type" or rule.get("optional") or "format" in rule:
                continue
            assert field in BUILTIN_DEFAULTS, f"{field} has no declared default"
            value = BUILTIN_DEFAULTS[field]
            # exact type: rejects bools for int fields (register_schema does)
            assert type(value) is rule["type"], field
            if "enum" in rule:
                assert value in rule["enum"], field
